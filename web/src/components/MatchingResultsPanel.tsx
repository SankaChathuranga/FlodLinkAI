import { useState, useEffect, useCallback } from 'react'
import { useAppContext } from '../context/AppContext'

// Member B: shows the Logistics/Matching Agent result for one workflow run inside the Triage Plan Viewer.

interface WorkflowRunDTO {
  id: string
  currentState: string
  failedAtState?: string | null
}

interface AllocationRowDTO {
  id: number
  depotId: number
  depotName: string
  shelterId: number
  shelterName: string
  itemName: string
  quantity: number
  status: string
}

interface AllocationProposalDTO {
  allocationProposalId: number
  unfulfillable: { shelterId: number; itemName: string; reason: string }[]
}

interface MatchingResultsPanelProps {
  workflowRunId: string
  refreshKey: number
}

export function MatchingResultsPanel({ workflowRunId, refreshKey }: MatchingResultsPanelProps) {
  const { apiBaseUrl } = useAppContext()

  const [run, setRun] = useState<WorkflowRunDTO | null>(null)
  const [proposal, setProposal] = useState<AllocationProposalDTO | null>(null)
  const [allocations, setAllocations] = useState<AllocationRowDTO[]>([])
  const [loading, setLoading] = useState<boolean>(true)
  const [running, setRunning] = useState<boolean>(false)
  const [error, setError] = useState<string | null>(null)

  const loadMatching = useCallback(async () => {
    setLoading(true)
    setError(null)

    try {
      const runResponse = await fetch(`${apiBaseUrl}/api/workflows/${workflowRunId}`)
      if (runResponse.status === 404) {
        setRun(null)
        setProposal(null)
        setAllocations([])
        return
      }
      if (!runResponse.ok) throw new Error(`Failed to load workflow run (HTTP ${runResponse.status})`)
      setRun(await runResponse.json())

      // 404 means Matching has not produced a proposal for this run yet.
      const proposalResponse = await fetch(`${apiBaseUrl}/api/workflows/${workflowRunId}/allocation-proposal`)
      setProposal(proposalResponse.ok ? await proposalResponse.json() : null)

      const allocationsResponse = await fetch(`${apiBaseUrl}/api/allocations?workflowRunId=${workflowRunId}`)
      setAllocations(allocationsResponse.ok ? await allocationsResponse.json() : [])
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load matching results.')
    } finally {
      setLoading(false)
    }
  }, [apiBaseUrl, workflowRunId])

  useEffect(() => {
    loadMatching()
  }, [loadMatching, refreshKey])

  const handleRunMatching = async () => {
    setRunning(true)
    setError(null)

    try {
      const response = await fetch(`${apiBaseUrl}/api/workflows/${workflowRunId}/advance`, { method: 'POST' })
      if (!response.ok) {
        const errData = await response.json().catch(() => null)
        throw new Error(errData?.detail || `Matching failed with HTTP ${response.status}`)
      }
      await loadMatching()
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to run the matching agent.')
    } finally {
      setRunning(false)
    }
  }

  if (loading) {
    return (
      <div className="bg-white p-6 rounded-xl border border-slate-200 animate-pulse space-y-3">
        <div className="h-5 bg-slate-200 rounded w-1/3"></div>
        <div className="h-16 bg-slate-100 rounded"></div>
      </div>
    )
  }

  const matchingFailed = run?.currentState === 'Failed' && run.failedAtState === 'Matching'
  const totalUnits = allocations.reduce((sum, a) => sum + a.quantity, 0)

  return (
    <div className="bg-white p-6 rounded-xl border border-slate-200 shadow-sm space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b pb-3">
        <div>
          <span className="text-xs text-emerald-600 uppercase tracking-wider font-mono font-bold">
            Logistics / Matching Agent
          </span>
          <h3 className="text-lg font-bold text-slate-900">Allocation Proposal</h3>
        </div>
        {run && (
          <span className="px-3 py-1 bg-slate-100 border border-slate-300 text-slate-700 text-xs font-mono rounded-lg">
            State: {run.currentState}
          </span>
        )}
      </div>

      {error && (
        <div className="bg-rose-50 border border-rose-200 text-rose-800 p-3 rounded-lg text-xs">{error}</div>
      )}

      {/* Plan created by "Trigger AI Triage" bypasses the workflow, so it can't be matched. */}
      {(!run || run.currentState === 'Triage') && (
        <p className="text-sm text-slate-500">
          This plan was generated by a single-report triage trigger, outside the workflow pipeline. Use{' '}
          <span className="font-semibold">Run Matching</span> above to start a workflow and match its needs against
          depot stock.
        </p>
      )}

      {run?.currentState === 'Matching' && (
        <div className="flex flex-wrap items-center justify-between gap-3 bg-emerald-50 border border-emerald-200 p-4 rounded-lg">
          <p className="text-sm text-emerald-900">Triage is complete. This run is waiting for the Matching Agent.</p>
          <button
            disabled={running}
            onClick={handleRunMatching}
            className="px-4 py-1.5 bg-emerald-700 hover:bg-amber-500 text-white rounded text-xs font-semibold disabled:opacity-50 transition"
          >
            {running ? 'Running Agent...' : 'Run Matching Agent'}
          </button>
        </div>
      )}

      {matchingFailed && (
        <div className="bg-amber-50 border border-amber-200 text-amber-900 p-4 rounded-lg text-sm">
          <span className="font-semibold">No stock available.</span> None of the triaged needs matched depot inventory,
          so the run stopped at Matching (NO_STOCK_AVAILABLE).
        </div>
      )}

      {proposal && (
        <>
          <div className="grid grid-cols-3 gap-3">
            <div className="bg-slate-50 border border-slate-200 rounded-lg p-3">
              <p className="text-[10px] uppercase tracking-wide text-slate-500 font-bold">Allocations</p>
              <p className="text-xl font-bold text-slate-900">{allocations.length}</p>
            </div>
            <div className="bg-slate-50 border border-slate-200 rounded-lg p-3">
              <p className="text-[10px] uppercase tracking-wide text-slate-500 font-bold">Units allocated</p>
              <p className="text-xl font-bold text-slate-900">{totalUnits}</p>
            </div>
            <div className="bg-slate-50 border border-slate-200 rounded-lg p-3">
              <p className="text-[10px] uppercase tracking-wide text-slate-500 font-bold">Unfulfillable</p>
              <p className="text-xl font-bold text-slate-900">{proposal.unfulfillable.length}</p>
            </div>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead className="bg-slate-100 text-slate-600 uppercase tracking-wide">
                <tr>
                  <th className="px-3 py-2">Depot</th>
                  <th className="px-3 py-2">Shelter</th>
                  <th className="px-3 py-2">Item</th>
                  <th className="px-3 py-2 text-right">Quantity</th>
                  <th className="px-3 py-2">Status</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {allocations.map((a) => (
                  <tr key={a.id} className="text-slate-800">
                    <td className="px-3 py-2">{a.depotName || `Depot #${a.depotId}`}</td>
                    <td className="px-3 py-2">{a.shelterName || `Shelter #${a.shelterId}`}</td>
                    <td className="px-3 py-2">{a.itemName}</td>
                    <td className="px-3 py-2 text-right font-mono">{a.quantity}</td>
                    <td className="px-3 py-2">
                      <span className="px-2 py-0.5 rounded-full bg-blue-50 border border-blue-200 text-blue-800 font-semibold">
                        {a.status}
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {proposal.unfulfillable.length > 0 ? (
            <div className="bg-slate-50 border-l-4 border-amber-500 p-3.5 rounded-r-lg space-y-1">
              <h5 className="text-xs font-bold text-slate-700 uppercase tracking-wide">Unfulfillable Needs</h5>
              {proposal.unfulfillable.map((gap, idx) => (
                <p key={`${gap.shelterId}-${gap.itemName}-${idx}`} className="text-xs text-slate-700">
                  Shelter #{gap.shelterId} &bull; {gap.itemName}: {gap.reason}
                </p>
              ))}
            </div>
          ) : (
            <p className="text-xs text-emerald-700 font-medium">Every triaged need was fully covered from depot stock.</p>
          )}
        </>
      )}
    </div>
  )
}
